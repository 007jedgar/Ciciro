// Regenerates src/lib/changelog-data.generated.ts from docs/CHANGELOG.md.
//
// Ciciro deploys to a Cloudflare Worker with no filesystem at request time,
// so the cron job that sends the product-update email (src/lib/email/cron.ts)
// and the /changelog page cannot fs.readFileSync the changelog themselves —
// this script does that once, at build time, and bakes the result into a
// plain, bundlable TS module both of them import as ordinary data.
//
// Run with: node scripts/generate-changelog-data.ts
// Wired into `npm run dev` and scripts/build.mjs, so it stays fresh; also
// committed, so `npm test` and `npm run typecheck` (which do not run either)
// see current data. test/changelog.test.ts fails if it drifts from
// docs/CHANGELOG.md, so CI catches a forgotten regeneration.
//
// Dates: every bullet needs a leading `<!-- YYYY-MM-DD -->` comment (see
// src/lib/changelog-parse.ts). Adding one by hand is the documented
// convention — write the date you're adding the entry — but this script
// backfills a missing one automatically, so forgetting it only costs
// precision, never breaks the build: it asks git for the oldest commit
// whose diff introduced that bullet's text and uses that commit's date, or
// today's date when git has never seen the text (a new, uncommitted entry).
// The backfilled comment is written back into docs/CHANGELOG.md so the date
// stays stable once committed, instead of drifting to "today" on every run.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";
import { parseChangelogEntries } from "../src/lib/changelog-parse.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const changelogPath = join(root, "docs/CHANGELOG.md");

const DATE_COMMENT = /^<!--\s*\d{4}-\d{2}-\d{2}\s*-->\s*/;

function today(): string {
  return new Date().toISOString().slice(0, 10);
}

/** The oldest commit date whose diff of docs/CHANGELOG.md contains `snippet`, or null if git has never seen it. */
function dateIntroduced(snippet: string): string | null {
  const result = spawnSync(
    "git",
    ["log", "--format=%ad", "--date=short", "-S", snippet, "--", "docs/CHANGELOG.md"],
    { cwd: root, encoding: "utf8" }
  );
  if (result.status !== 0 || !result.stdout.trim()) return null;
  const dates = result.stdout.trim().split("\n");
  return dates[dates.length - 1] ?? null; // git log is newest-first; the last line is the oldest.
}

/** A substring of the bullet's first line unique enough for `git log -S`, but short enough to not be a shell/arg-length problem. */
function snippetOf(firstLine: string): string {
  return firstLine.replace(/^- /, "").trim().slice(0, 60);
}

/** Adds a `<!-- YYYY-MM-DD -->` comment to any top-level bullet under "## Unreleased" that doesn't already start with one. */
function backfillMissingDates(markdown: string): { markdown: string; changed: boolean } {
  const lines = markdown.split("\n");
  const start = lines.findIndex((line) => line.trim() === "## Unreleased");
  if (start === -1) return { markdown, changed: false };
  const end = lines.findIndex((line, i) => i > start && /^## /.test(line));
  const sectionEnd = end === -1 ? lines.length : end;

  let changed = false;
  for (let i = start + 1; i < sectionEnd; i++) {
    if (!/^- /.test(lines[i])) continue;
    const rest = lines[i].slice(2);
    if (DATE_COMMENT.test(rest)) continue;
    const date = dateIntroduced(snippetOf(lines[i])) ?? today();
    lines[i] = `- <!-- ${date} --> ${rest}`;
    changed = true;
  }
  return { markdown: lines.join("\n"), changed };
}

const original = readFileSync(changelogPath, "utf8");
const { markdown: changelog, changed } = backfillMissingDates(original);
if (changed) {
  writeFileSync(changelogPath, changelog);
  console.log("Backfilled missing changelog entry dates in docs/CHANGELOG.md");
}

const entries = parseChangelogEntries(changelog);

const out = `// AUTO-GENERATED by scripts/generate-changelog-data.ts from docs/CHANGELOG.md.
// Do not hand-edit — run \`node scripts/generate-changelog-data.ts\` instead.

import type { ChangelogEntry } from "@/lib/changelog-parse";

export const CHANGELOG_ENTRIES: ChangelogEntry[] = ${JSON.stringify(entries, null, 2)};
`;

writeFileSync(join(root, "src/lib/changelog-data.generated.ts"), out);
console.log(`Wrote ${entries.length} changelog entries to src/lib/changelog-data.generated.ts`);
